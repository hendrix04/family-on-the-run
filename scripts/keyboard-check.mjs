import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const page = await browser.newPage({ viewport: { width: 2560, height: 1440 }, hasTouch: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const keyboard = page.getByRole('group', { name: 'On-screen keyboard', exact: true });
const tap = name => keyboard.getByRole('button', { name, exact: true }).tap();
try {
  await page.goto('http://127.0.0.1:3000/v1/database/family-on-the-run/route/');
  const password = page.getByLabel('Household access code');
  await password.tap();
  await keyboard.waitFor();
  await tap('a');
  assert.equal(await password.inputValue(), 'a');
  assert.equal(await password.getAttribute('type'), 'password');
  await tap('Done');
  await keyboard.waitFor({ state: 'hidden' });
  await password.fill((await readFile('.spacetime/access-code', 'utf8')).trim());
  await page.getByRole('button', { name: 'Connect this screen', exact: true }).click();
  await page.getByRole('heading', { name: 'Lindsay To Do' }).waitFor();
  const column = page.locator('.task-column').filter({ has: page.getByRole('heading', { name: 'Lindsay To Do' }) });
  await column.getByRole('button', { name: 'Add a task', exact: true }).click();
  const input = page.getByRole('textbox', { name: 'New task for Lindsay' });
  await keyboard.waitFor();
  await tap('Shift'); await tap('A'); await tap('b'); await tap('Space'); await tap('c');
  assert.equal(await input.inputValue(), 'Ab c');
  await input.evaluate(field => field.setSelectionRange(1, 3));
  await tap('x');
  assert.equal(await input.inputValue(), 'Axc');
  await tap('Backspace');
  assert.equal(await input.inputValue(), 'Ac');
  await tap('Symbols'); await tap('@'); await tap('/');
  assert.equal(await input.inputValue(), 'A@/c');
  await tap('ABC');
  await input.fill('x'.repeat(200)); await tap('a');
  assert.equal((await input.inputValue()).length, 200);
  await input.fill('a😀'); await tap('Backspace');
  assert.equal(await input.inputValue(), 'a');
  await input.fill('Keyboard submit check');
  await input.evaluate(field => field.form.addEventListener('submit', event => {
    event.preventDefault(); event.stopImmediatePropagation(); field.dataset.submitted = 'yes';
  }, { capture: true, once: true }));
  await tap('Enter');
  assert.equal(await input.getAttribute('data-submitted'), 'yes', 'Enter submits the active form');
  await input.fill('');
  await tap('Done');
  await page.getByRole('button', { name: 'Add an event', exact: true }).click();
  const eventName = page.getByRole('textbox', { name: 'Event name' });
  await eventName.tap();
  await keyboard.waitFor();
  await tap('h'); await tap('i');
  assert.equal(await eventName.inputValue(), 'hi');
  assert.ok(await keyboard.evaluate(element => element.closest('dialog')?.open), 'Keyboard works within modal focus scope');
  await mkdir('.spacetime/screenshots', { recursive: true });
  await page.screenshot({ path: '.spacetime/screenshots/keyboard-2560.png' });
  await tap('Done');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await keyboard.waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 390, height: 844 });
  await input.tap();
  assert.equal(await keyboard.isVisible(), false, 'Mobile uses its native keyboard');
  assert.deepEqual(errors, []);
  console.log('PASS: touch keyboard, password masking, Shift, symbols, selection replacement, Unicode backspace, length limits, dismissal, modal input, Enter submission, and mobile behavior.');
} finally { await browser.close(); }
